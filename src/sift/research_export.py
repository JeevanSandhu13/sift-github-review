def build_replication_package(
    cwd: Path,
    dest: Path,
    *,
    include_scripts: bool = True,
) -> dict[str, Any]:
    """Build a new replication package and publish it atomically.

    An existing destination is never reused: stale result or script files
    from an older, broader export could otherwise survive and silently bypass
    today's export policy.  Work is assembled in a private sibling directory
    and renamed into place only after every required artifact succeeds, so a
    crash cannot leave a package that looks complete but is only half written.
    """
    requested = Path(dest)
    if requested.exists():
        raise FileExistsError(f"export destination already exists: {requested}")
    requested.parent.mkdir(parents=True, exist_ok=True)
    stage = Path(tempfile.mkdtemp(
        prefix=f".{requested.name}.building-", dir=requested.parent,
    ))
    try:
        summary = _build_replication_package_into(
            cwd, stage, include_scripts=include_scripts,
        )
        if requested.exists():
            raise FileExistsError(
                f"export destination appeared during build: {requested}",
            )
        os.replace(stage, requested)
    except BaseException:
        shutil.rmtree(stage, ignore_errors=True)
        raise
    summary["destination"] = str(requested)
    try:
        from sift.reproducibility import append_audit_event
        event = append_audit_event(cwd, "replication_export", {
            "export_kind": "replication_package",
            "bundle_manifest_sha256": summary.get("bundle_manifest_sha256"),
            "status": "published",
        })
        summary["reproducibility_audit"] = {
            "status": "recorded", "sequence": event["sequence"],
        }
    except Exception as exc:  # noqa: BLE001 — export is valid; audit is explicit
        summary["reproducibility_audit"] = {
            "status": "unavailable", "reason": type(exc).__name__,
        }
    return summary


def _build_replication_package_into(
    cwd: Path,
    dest: Path,
    *,
    include_scripts: bool = True,
) -> dict[str, Any]:
    """Assemble a replication package for the session at ``cwd``.

    Layout::

        <dest>/
          README.md               orientation + how to re-run
          METHODS.md              per-result methods, N, verification
          environment.json        software versions
          scripts/                every script Sift ran, in order
          results/                sanitized result payloads (JSON)
          tables/                 markdown + LaTeX per result
          disclosure/             release ledger + chain verification

    Returns a summary dict for the caller to surface. Raises only for
    genuinely exceptional conditions (unwritable destination); missing
    optional material degrades to an omitted section rather than a
    failed export.
    """
    cwd = Path(cwd)
    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)

    from sift.policy import is_exportable, load_policy
    from sift.store import get_store
    store = get_store(cwd)
    results = [r for r in store.list_all() if r.sanitized_payload]

    # Exclude results computed from a dataset the researcher has
    # marked non-exportable -- same policy check ``_gather_report_material``
    # applies for the Markdown/HTML/PDF/PowerPoint report formats (see
    # its docstring for the full rationale: this is a STRONGER
    # restriction than "the result is SDC-safe", since some data-use
    # agreements prohibit even the fact of having analysed a dataset
    # from appearing in anything that leaves the session). The
    # replication package is the most complete export surface Sift
    # has -- full result JSON, rendered tables, and the exact script
    # code that produced them, all written to a directory meant to
    # leave the machine -- so it must never have been the one export
    # path that skipped this check entirely, which it was until this
    # fix. ``r.source_dataset`` is the store row's own column, not
    # something read from the payload (no sanitizer shape carries a
    # "source_dataset" payload key).
    policy_doc = load_policy(cwd)
    excluded_dataset_count = 0
    filtered_results = []
    for r in results:
        sources = r.all_source_datasets
        if any(
            not is_exportable(policy_doc, Path(src).name) for src in sources
        ):
            excluded_dataset_count += 1
            continue
        filtered_results.append(r)
    results = filtered_results

    (dest / "results").mkdir(exist_ok=True)
    (dest / "tables").mkdir(exist_ok=True)
    if include_scripts:
        (dest / "scripts").mkdir(exist_ok=True)
    (dest / "disclosure").mkdir(exist_ok=True)
    (dest / "provenance").mkdir(exist_ok=True)
    (dest / "workflow").mkdir(exist_ok=True)

    n_tables = 0
    n_scripts = 0
    seen_scripts: set[str] = set()
    methods_rows: list[str] = []
    script_paths_by_run: dict[str, str] = {}
    result_paths_by_run: dict[str, list[dict[str, str]]] = {}

    for idx, row in enumerate(results, start=1):
        stem = f"{idx:03d}_{_slug(row.label or row.analysis_type)}"

        result_relative = f"results/{stem}.json"
        run_key = row.script_run_id or row.id
        (dest / result_relative).write_text(
            json.dumps(
                {
                    "id": row.id,
                    "label": row.label,
                    "analysis_type": row.analysis_type,
                    "language": row.language,
                    "created_at": row.created_at,
                    "script_run_id": row.script_run_id,
                    "source_dataset": row.source_dataset,
                    "source_datasets": list(row.all_source_datasets),
                    "transformations": row.transformations,
                    "provenance": row.provenance,
                    "lifecycle": {
                        "status": row.lifecycle_status,
                        "supersedes_result_id": row.supersedes_result_id,
                        "superseded_by": row.superseded_by,
                        "correction_reason": row.correction_reason,
                    },
                    "payload": row.sanitized_payload,
                },
                indent=2, ensure_ascii=False,
            ),
            encoding="utf-8",
        )
        result_paths_by_run.setdefault(run_key, []).append({
            "result_id": row.id,
            "result": result_relative,
        })

        # Table rendering is per-result and best-effort: a payload
        # that defeats one renderer must not cost the researcher the
        # entire package. The result JSON above is already written, so
        # nothing is lost but the formatted view.
        try:
            md = render_table(row.sanitized_payload)
        except Exception:  # noqa: BLE001
            md = None
        try:
            tex = render_latex_table(
                row.sanitized_payload,
                caption=row.label or row.analysis_type,
                label=f"tab:{stem}",
            )
        except Exception:  # noqa: BLE001
            tex = None
        if md:
            (dest / "tables" / f"{stem}.md").write_text(md, encoding="utf-8")
            n_tables += 1
        if tex:
            (dest / "tables" / f"{stem}.tex").write_text(tex, encoding="utf-8")

        # One file per *script run*, not per result: a batch script
        # that emitted 24 results is still one script, and writing it
        # 24 times would make the package look padded and the run
        # order unreadable. Keyed on ``script_run_id`` where present,
        # falling back to the row id for pre-batch-format rows.
        if include_scripts and row.script_code:
            key = run_key
            if key not in seen_scripts:
                seen_scripts.add(key)
                ext = {"R": "R", "Stata": "do", "Python": "py"}.get(
                    row.language, "txt")
                script_relative = f"scripts/{stem}.{ext}"
                # Preserve the exact source bytes used for provenance hashing.
                # Text-mode writes translate LF to CRLF on Windows, which
                # would make an unchanged exported script fail its own
                # recorded SHA-256 and break model-free reproduction.
                (dest / script_relative).write_bytes(
                    row.script_code.encode("utf-8")
                )
                script_paths_by_run[key] = script_relative
                n_scripts += 1

        methods_rows.append(_methods_entry(idx, row))

    # Machine-readable lineage using the W3C PROV entity/activity model:
    # datasets and stored results are entities; one script run is the
    # activity that used the former and generated the latter. Keeping this
    # compact JSON (rather than inventing an opaque graph format) makes a
    # replication package immediately auditable by people and programs.
    dataset_entities: dict[str, dict[str, Any]] = {}
    for row in results:
        hashes = row.provenance.get("dataset_hashes", {}) if row.provenance else {}
        fingerprints = row.provenance.get("canonical_fingerprints", {}) if row.provenance else {}
        for source in row.all_source_datasets:
            entity = dataset_entities.setdefault(source, {
                "id": source, "type": "dataset",
            })
            if isinstance(hashes, dict) and hashes.get(source):
                entity["content_sha256"] = hashes[source]
            if isinstance(fingerprints, dict) and fingerprints.get(source):
                entity["canonical_fingerprint"] = fingerprints[source]
    activities: dict[str, dict[str, Any]] = {}
    for row in results:
        activity_id = row.script_run_id or f"legacy-run:{row.id}"
        activity = activities.setdefault(activity_id, {
            "id": activity_id,
            "type": "script_execution",
            "language": row.language,
            "used": list(row.all_source_datasets),
            "generated": [],
            "script_sha256": row.provenance.get("script_sha256"),
            "workflow_id": row.provenance.get("workflow_id"),
            "workflow_revision": row.provenance.get("workflow_revision"),
        })
        activity["generated"].append(row.id)
    claim_entities: list[dict[str, Any]] = []
    try:
        from sift.research_workflow import list_evidence_claims
        for claim in list_evidence_claims(cwd):
            if isinstance(claim.get("result_ids"), list):
                claim_entities.append({
                    "id": claim.get("id"), "type": "evidence_bound_claim",
                    "wasDerivedFrom": claim["result_ids"],
                    "status": claim.get("status"),
                })
    except Exception:  # noqa: BLE001 — provenance enrichment is best-effort
        pass
    (dest / "provenance" / "lineage.json").write_text(
        json.dumps({
            "version": 1,
            "model": "W3C PROV entity/activity",
            "entities": {
                "datasets": [
                    dataset_entities[source] for source in sorted(dataset_entities)
                ],
                "results": [
                    {
                        "id": row.id, "type": "sanitized_result",
                        "analysis_id": row.provenance.get("analysis_id"),
                        "analysis_role": row.provenance.get("analysis_role"),
                        "lifecycle_status": row.lifecycle_status,
                    }
                    for row in results
                ],
                "narrative_claims": claim_entities,
            },
            "activities": list(activities.values()),
        }, indent=2, ensure_ascii=False),
        encoding="utf-8",
    )

    # Durable methodological state completes question -> plan -> data -> code
    # -> result -> claim lineage. Researcher notes are intentionally excluded:
    # they are local-only and may contain sensitive context or raw values.
    for filename in ("research_workflow.json", "project_memory.json"):
        workflow_source = cwd / ".sift" / filename
        try:
            if workflow_source.is_file():
                shutil.copyfile(workflow_source, dest / "workflow" / filename)
        except OSError:
            pass

    # Environment and exact model-free reconstruction contract.
    environment = capture_environment()
    (dest / "environment.json").write_text(
        json.dumps(environment, indent=2), encoding="utf-8")

    reproducible_datasets: dict[str, dict[str, Any]] = {}
    reproducible_runs: dict[str, dict[str, Any]] = {}
    for row in results:
        provenance = row.provenance or {}
        source_hashes = provenance.get("source_file_hashes", {})
        content_hashes = provenance.get("dataset_hashes", {})
        fingerprints = provenance.get("canonical_fingerprints", {})
        parser_versions = provenance.get("parser_versions", {})
        dataset_selections = provenance.get("dataset_selections", {})
        for source in row.all_source_datasets:
            reproducible_datasets.setdefault(source, {
                "path": source,
                # Reruns use the original source bytes. A canonical content
                # hash is not interchangeable with the source-file hash.
                "source_sha256": (
                    source_hashes.get(source) if isinstance(source_hashes, dict)
                    else None
                ),
                "content_sha256": (
                    content_hashes.get(source) if isinstance(content_hashes, dict)
                    else None
                ),
                "canonical_fingerprint": (
                    fingerprints.get(source) if isinstance(fingerprints, dict)
                    else None
                ),
                "parser": (
                    parser_versions.get(source) if isinstance(parser_versions, dict)
                    else None
                ),
                "selection": (
                    dataset_selections.get(source)
                    if isinstance(dataset_selections, dict) else None
                ),
            })
        run_key = row.script_run_id or row.id
        if run_key not in reproducible_runs:
            script_relative_path = script_paths_by_run.get(run_key)
            actual_script_sha256 = (
                hashlib.sha256(
                    (dest / script_relative_path).read_bytes()
                ).hexdigest()
                if script_relative_path else None
            )
            recorded_script_sha256 = provenance.get("script_sha256")
            reproducible_runs[run_key] = {
                "script_run_id": run_key,
                "language": row.language,
                "script": script_relative_path,
                "script_sha256": actual_script_sha256,
                "recorded_script_sha256": recorded_script_sha256,
                "script_hash_matches_record": (
                    actual_script_sha256 == recorded_script_sha256
                    if recorded_script_sha256 else None
                ),
                "executed_at": provenance.get("executed_at") or row.created_at,
                "result_schema_version": provenance.get("result_schema_version"),
                "verification_schema_version": provenance.get(
                    "verification_schema_version"
                ),
                "model_configuration": provenance.get("model_configuration", {}),
                "privacy_configuration": provenance.get("privacy_configuration", {}),
                "execution_environment": provenance.get("execution_environment", {}),
                "host_package_versions": provenance.get("host_package_versions", {}),
                "workflow_id": provenance.get("workflow_id"),
                "workflow_revision": provenance.get("workflow_revision"),
                "expected_results": result_paths_by_run.get(run_key, []),
                "runnable": bool(script_relative),
            }

    audit_source = cwd / ".sift" / "reproducibility_audit.jsonl"
    audit_status: dict[str, Any]
    try:
        from sift.reproducibility import verify_audit_bytes
        if audit_source.is_file():
            audit_bytes = audit_source.read_bytes()
            audit_status = verify_audit_bytes(audit_bytes)
            (dest / "provenance" / "reproducibility_audit.jsonl").write_bytes(
                audit_bytes
            )
        else:
            audit_status = verify_audit_bytes(b"")
    except OSError as exc:
        audit_status = {"valid": False, "reason": type(exc).__name__}

    reproduce = {
        "format": "sift-model-free-reproduction",
        "version": 1,
        "model_required": False,
        "datasets": [
            reproducible_datasets[key] for key in sorted(reproducible_datasets)
        ],
        "runs": list(reproducible_runs.values()),
        "environment": {
            "platform": environment.get("platform"),
            "platform_release": environment.get("platform_release"),
            "machine": environment.get("machine"),
            "packages": {
                "python": environment.get("python_version"),
                **environment.get("python_packages", {}),
            },
        },
        "audit_chain": audit_status,
        "comparison": {"rtol": 1e-7, "atol": 1e-10},
    }
    (dest / "reproduce.json").write_text(
        json.dumps(reproduce, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    # Disclosure material
    ledger_snapshot = release_ledger.ledger_snapshot(cwd)
    chain_ok = ledger_snapshot.integrity_ok
    n_records = ledger_snapshot.record_count
    detail = ledger_snapshot.detail
    if ledger_snapshot.ledger_bytes is not None:
        (dest / "disclosure" / "release_ledger.jsonl").write_bytes(
            ledger_snapshot.ledger_bytes,
        )
    if ledger_snapshot.health_bytes is not None:
        (
            dest / "disclosure" / release_ledger.LEDGER_HEALTH_FILENAME
        ).write_bytes(ledger_snapshot.health_bytes)
    (dest / "disclosure" / "disclosure_report.md").write_text(
        build_disclosure_report(cwd, snapshot=ledger_snapshot),
        encoding="utf-8",
    )

    methods_text = _methods_document(methods_rows)
    methods_text += (
        "\n## AI-use disclosure statement\n\n"
        "For a methods section or journal disclosure form; generated "
        "from this session's records:\n\n> "
        + ai_use_statement(cwd) + "\n"
    )
    (dest / "METHODS.md").write_text(methods_text, encoding="utf-8")
    (dest / "README.md").write_text(
        _readme_document(
            n_results=len(results), n_scripts=n_scripts, n_tables=n_tables,
            chain_ok=chain_ok, n_records=n_records,
            excluded_datasets=excluded_dataset_count,
        ),
        encoding="utf-8",
    )

    # This is deliberately last: every published artifact except the
    # manifest itself is covered, so additions, removals, or edits are all
    # detectable before a model-free rerun begins.
    from sift.reproducibility import build_bundle_manifest
    bundle_manifest = build_bundle_manifest(dest)

    return {
        "ok": True,
        "destination": str(dest),
        "results": len(results),
        "scripts": n_scripts,
        "tables": n_tables,
        "ledger_records": n_records,
        "ledger_chain_ok": chain_ok,
        "ledger_detail": detail,
        "excluded_datasets": excluded_dataset_count,
        "bundle_files": len(bundle_manifest["files"]),
        "bundle_manifest_sha256": bundle_manifest["manifest_sha256"],
        "audit_chain_ok": audit_status.get("valid", False),
    }


def _slug(text: str, max_len: int = 40) -> str:
    """Filesystem-safe stem from a researcher/model-authored label."""
    keep = [c if (c.isalnum() or c in "-_") else "_"
            for c in (text or "result").strip().lower().replace(" ", "_")]
    slug = "".join(keep).strip("_") or "result"
    while "__" in slug:
        slug = slug.replace("__", "_")
    return slug[:max_len]


def _methods_entry(idx: int, row: Any) -> str:
    payload = row.sanitized_payload or {}
    parts = [f"### {idx}. {row.label or row.analysis_type}", ""]
    parts.append(f"- Analysis type: `{row.analysis_type}`")
    parts.append(f"- Language: {row.language}")
    if row.provenance.get("analysis_role"):
        parts.append(f"- Analysis role: {row.provenance['analysis_role']}")
    if row.provenance.get("random_seed") is not None:
        parts.append(f"- Random seed: {row.provenance['random_seed']}")
    if row.lifecycle_status != "active":
        parts.append(
            f"- Lifecycle: {row.lifecycle_status}; replacement: "
            f"{row.superseded_by or '(not recorded)'}"
        )
    if row.all_source_datasets:
        parts.append(
            "- Source dataset(s): "
            + ", ".join(f"`{source}`" for source in row.all_source_datasets)
        )
    n = payload.get("n")
    if isinstance(n, int):
        parts.append(f"- Observations: {n:,}")
    for key, disp in (("response_variable", "Outcome"),
                      ("predictor_variables", "Predictors"),
                      ("variable", "Variable")):
        val = payload.get(key)
        if isinstance(val, list) and val:
            parts.append(f"- {disp}: {', '.join(str(v) for v in val)}")
        elif isinstance(val, str) and val:
            parts.append(f"- {disp}: {val}")
    robust = payload.get("robust_se_type")
    if robust:
        parts.append(f"- Standard errors: {robust}")
    ver = verify_payload(payload)
    if ver:
        for check in ver["checks"]:
            mark = "PASS" if check["status"] == "pass" else "WARN"
            parts.append(f"- [{mark}] {check['detail']}")
    if row.transformations:
        parts.append("- Disclosure control applied:")
        for tr in row.transformations:
            parts.append(f"  - {tr}")
    parts.append("")
    return "\n".join(parts)


def _methods_document(entries: list[str]) -> str:
    head = """# Methods

Generated by Sift from stored analysis results. Every figure below is
the disclosure-controlled value that was produced at analysis time —
nothing here was written or paraphrased by a language model.

Verification lines marked `[WARN]` are deterministic checks that did
not pass; they are reported here rather than omitted. A check that is
absent was not computed, which is not the same as passing.

"""
    return head + ("\n".join(entries) if entries else "_No results recorded._\n")


def _readme_document(*, n_results: int, n_scripts: int, n_tables: int,
                     chain_ok: bool, n_records: int,
                     excluded_datasets: int = 0) -> str:
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    chain_line = (
        f"verified across {n_records} records"
        if chain_ok else
        "**INCONSISTENT — see disclosure/disclosure_report.md**"
    )
    excluded_line = (
        f"{excluded_datasets} result(s) computed from a dataset marked "
        "`exportable: false` in this session's policy were excluded "
        "from this package on that basis.\n\n"
        if excluded_datasets else ""
    )
    return f"""# Replication package

Generated by Sift on {stamp}.

## Contents

| Path | What it holds |
|---|---|
| `scripts/` | The {n_scripts} analysis script(s) Sift executed, as run |
| `results/` | {n_results} disclosure-controlled result payload(s), JSON |
| `tables/` | {n_tables} table(s), Markdown and LaTeX (`booktabs`) |
| `METHODS.md` | Per-result methods, sample sizes, verification verdicts |
| `environment.json` | Software versions used |
| `provenance/lineage.json` | Question/data/code/result/claim lineage with dataset and script hashes |
| `workflow/` | Approved research intent, primary/sensitivity plan, assumptions, and seeds |
| `disclosure/` | Release ledger and disclosure report |

## What is and is not here

{excluded_line}This package contains **no raw data**. The result payloads passed
through Sift's statistical-disclosure-control layer before they were
stored: small cells are suppressed, precision is clamped to the
sample size, and per-observation quantities were never retained.
Scripts are included because they are needed to reproduce the work;
they reference variable names, not values.

To reproduce, supply the original dataset and run the scripts in
`scripts/` in filename order using the versions in
`environment.json`.

## Disclosure record

The release ledger records every result that was sent to the external
model during this analysis. Hash chain: {chain_line}.

The ledger is tamper-evident, not tamper-proof: it detects edits,
deletions and reordering of its own records. It is an accounting
record of what was disclosed. It is not a formal privacy guarantee
and makes no claim about what can be inferred from the disclosures
taken together.
"""


# ---------------------------------------------------------------------------
# Disclosure report (IRB / data governance)
# ---------------------------------------------------------------------------

def build_disclosure_report(
    cwd: Path, *, snapshot: release_ledger.LedgerSnapshot | None = None,
) -> str:
    """Render a reviewable disclosure report from the release ledger.

    Written for a reader who is deciding whether this workflow is
    acceptable under a data-use agreement or IRB protocol, not for the
    researcher who already knows what they did. States scope and
    limits explicitly rather than implying stronger guarantees than
    the implementation provides.
    """
    cwd = Path(cwd)
    snapshot = snapshot or release_ledger.ledger_snapshot(cwd)
    records = list(snapshot.records)
    chain_ok = snapshot.integrity_ok
    n_records = snapshot.record_count
    detail = snapshot.detail
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    by_tool: dict[str, int] = {}
    datasets: set[str] = set()
    plot_releases = 0
    for rec in records:
        tool = str(rec.get("tool") or rec.get("kind") or "unknown")
        by_tool[tool] = by_tool.get(tool, 0) + 1
        if rec.get("kind") == "plot_vision":
            plot_releases += 1
        args = rec.get("args") or {}
        facts = rec.get("facts") or {}
        for key in ("dataset",):
            if isinstance(args.get(key), str):
                datasets.add(args[key])
        if isinstance(facts.get("source_dataset"), str):
            datasets.add(facts["source_dataset"])
        for source in facts.get("source_datasets") or []:
            if isinstance(source, str):
                datasets.add(source)
        for result in facts.get("results") or []:
            if not isinstance(result, dict):
                continue
            if isinstance(result.get("source_dataset"), str):
                datasets.add(result["source_dataset"])
            for source in result.get("source_datasets") or []:
                if isinstance(source, str):
                    datasets.add(source)

    lines = [
        "# Disclosure report",
        "",
        f"Generated by Sift on {stamp}.",
        "",
        "## Scope",
        "",
        "This report lists information released from this machine to an "
        "external model provider during one analysis session. It is "
        "produced from Sift's release ledger, an append-only, "
        "hash-chained log written at the point of release.",
        "",
        "## Summary",
        "",
        f"- Total releases recorded: **{n_records}**",
        f"- Datasets referenced: **{len(datasets) or 'none recorded'}**",
        f"- Figure releases (model-output plots): **{plot_releases}**",
        f"- Hash chain: **{'verified' if chain_ok else 'INCONSISTENT'}**"
        + ("" if chain_ok else f" — {detail}"),
        "",
    ]

    if datasets:
        lines += ["### Datasets referenced", ""]
        lines += [f"- `{d}`" for d in sorted(datasets)]
        lines.append("")

    if by_tool:
        lines += ["### Releases by operation", "",
                  "| Operation | Count |", "|---|---|"]
        for tool, count in sorted(by_tool.items(), key=lambda kv: -kv[1]):
            lines.append(f"| `{tool}` | {count} |")
        lines.append("")

    lines += [
        "## What was released",
        "",
        "Each row is one release. `N` is the sample size behind the "
        "released statistic where the payload carried one. The payload "
        "hash identifies the exact released content without reproducing "
        "it here.",
        "",
        "| # | Time (UTC) | Operation | Subject | N | Payload hash |",
        "|---|---|---|---|---|---|",
    ]
    for i, rec in enumerate(records, start=1):
        args = rec.get("args") or {}
        facts = rec.get("facts") or {}
        extra = rec.get("extra") or {}
        fact_sources = facts.get("source_datasets")
        joined_sources = (
            " + ".join(fact_sources)
            if isinstance(fact_sources, list) else ""
        )
        subject = (args.get("dataset") or joined_sources
                   or facts.get("source_dataset")
                   or args.get("result_id") or extra.get("filename") or "")
        n_val = facts.get("n", "")
        ts = str(rec.get("ts", "")).replace("T", " ").replace("+00:00", "")
        digest = str(rec.get("response_sha256", ""))[:16]
        lines.append(
            f"| {i} | {ts} | `{rec.get('tool', rec.get('kind', ''))}` | "
            f"{subject} | {n_val} | `{digest}` |"
        )
    if not records:
        lines.append("| — | — | _no releases recorded_ | — | — | — |")

    lines += [
        "",
        "## Controls in force",
        "",
        "- **Closed tool surface.** The model reaches data only through "
        "an enumerated set of tools. It has no shell, no filesystem "
        "access, and no network access.",
        "- **Sandboxed execution.** Analysis scripts run under a "
        "deny-by-default sandbox with networking denied and read/write "
        "access restricted to the session directory.",
        "- **Statistical disclosure control.** Every result crossing to "
        "the model passes an allowlist plus SDC rules: small-cell "
        "suppression, precision clamping scaled to sample size, "
        "dominance checks, and minimum-N rejection.",
        "- **No raw data release.** Raw rows, raw program output, and "
        "per-observation quantities are never sent to the model.",
        "",
        "## Limits of this report",
        "",
        "This report records **what was released**. It does not bound "
        "what could be inferred from those releases in combination. "
        "Individually compliant releases can, in aggregate, narrow the "
        "range of possible underlying values. Sift performs formal epsilon "
        "composition only for explicitly enabled differential-privacy "
        "count queries; ordinary exact, suppressed releases remain governed "
        "by heuristic cumulative budgets rather than a universal formal "
        "privacy bound.",
        "",
        "The hash chain detects modification, deletion, or reordering "
        "of ledger records. It does not prevent them: the file is under "
        "the control of whoever controls the machine.",
        "",
    ]
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Analysis report
# ---------------------------------------------------------------------------
#
# The replication package is for a journal; the disclosure report is
# for a governance office. The analysis report is for a human reader —
# a co-author, a supervisor, the researcher themselves next month. One
# document: what was analysed, what was found, how much to trust each
# finding, what was disclosed along the way.
#
# Assembly rules, same posture as the other exports:
# - Every number comes from a stored sanitized payload. No LLM prose.
# - Verification verdicts are printed as computed, warnings first.
# - Figures are restricted to manifest-listed helper plots — the same
#   allowlist that gates what the model may see. The report is built
#   to be shareable, so it must not hold raw-data figures that the
#   rest of the pipeline deliberately withholds.
# - HTML output is fully self-contained (inline CSS, base64 images):
#   one file that can be mailed, printed, or dropped into a shared
#   drive without a directory of loose assets.

_REPORT_MAX_EMBED_BYTES = 3 * 1024 * 1024   # per figure, matches vision cap
_REPORT_MAX_FIGURES = 24


def _collect_report_figures(cwd: Path) -> list[dict[str, str]]:
    """Manifest-listed helper plots for the session, oldest first.

    Reuses the same manifest+kind allowlist that gates model vision
    (see ``runner._capture_plots``): a report is a shareable artifact,
    so it embeds only figures already cleared for crossing. Raw-data
    plots a script produced outside the helpers stay researcher-only,
    exactly as they do in chat.
    """
    import base64
    import json as _json

    from sift.runner import _PLOT_KIND_ALLOWLIST

    figures: list[dict[str, str]] = []
    runs_root = Path(cwd) / ".sift" / "runs"
    if not runs_root.is_dir():
        return figures
    try:
        run_dirs = sorted(d for d in runs_root.iterdir() if d.is_dir())
    except OSError:
        return figures
    for run_dir in run_dirs:
        manifest = run_dir / "_sift_plots" / "manifest.jsonl"
        if not manifest.is_file():
            continue
        try:
            lines = manifest.read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        for raw in lines:
            raw = raw.strip()
            if not raw:
                continue
            try:
                entry = _json.loads(raw)
            except ValueError:
                continue
            if not isinstance(entry, dict):
                continue
            kind = entry.get("kind")
            fname = entry.get("file") or entry.get("filename")
            if kind not in _PLOT_KIND_ALLOWLIST or not isinstance(fname, str):
                continue
            target = (run_dir / "_sift_plots" / Path(fname).name)
            # PNG only for embedding; PDF/EPS helper outputs have PNG
            # sidecars on macOS (sips) but not on other platforms —
            # skip quietly rather than embed something browsers can't
            # show inline.
            candidates = [target]
            if target.suffix.lower() != ".png":
                candidates.insert(0, target.with_suffix(
                    target.suffix + ".sift.png"))
            for cand in candidates:
                if not cand.is_file() or cand.suffix.lower() != ".png":
                    continue
                try:
                    blob = cand.read_bytes()
                except OSError:
                    continue
                if not blob or len(blob) > _REPORT_MAX_EMBED_BYTES:
                    continue
                figures.append({
                    "kind": str(kind),
                    "label": str(entry.get("label") or kind),
                    "b64": base64.b64encode(blob).decode("ascii"),
                })
                break
            if len(figures) >= _REPORT_MAX_FIGURES:
                return figures
    return figures


def _gather_report_material(cwd: Path) -> dict[str, Any]:
    """Assemble everything the analysis-report exporters need, once.

    Shared by the Markdown/HTML, PDF, and PowerPoint exporters so all
    three formats are built from exactly the same query against the
    store, the same policy-exclusion pass, and the same per-result
    verification/render calls -- there is no path by which one format
    could show a result, warning, or figure that another omits.
    """
    cwd = Path(cwd)
    from sift import release_ledger, usage_meter
    from sift.policy import is_exportable, load_policy
    from sift.store import get_store

    try:
        results = [r for r in get_store(cwd).list_all() if r.sanitized_payload]
    except Exception as exc:  # noqa: BLE001 — never misreport corruption as empty
        raise RuntimeError(
            f"analysis report could not read the result store ({type(exc).__name__})"
        ) from exc

    # Exclude results computed from a dataset the researcher has
    # marked non-exportable. This is a STRONGER restriction than "the
    # result itself is SDC-safe" (it already is, or it wouldn't be in
    # the store at all) — some data-use agreements prohibit even the
    # fact of having analysed a dataset from appearing in anything
    # that leaves the session, regardless of how aggregated the
    # result is. A result with no ``source_dataset`` at all (the
    # researcher didn't pass one to submit_script) is never excluded
    # here — there's nothing to check it against.
    policy_doc = load_policy(cwd)
    excluded_dataset_count = 0
    filtered_results = []
    for r in results:
        # ``r.source_dataset`` is the store row's own column -- what
        # submit_script actually recorded ``source_dataset`` as (see
        # store.py's ``StoreRow`` docstring). This must NOT be read
        # from ``r.sanitized_payload`` instead: no sanitizer analysis
        # shape has ever included a "source_dataset" key in the
        # payload itself, so a payload-based lookup here always
        # returns ``None`` -- which made this entire exclusion pass a
        # silent no-op for every report format that shares this
        # helper (Markdown/HTML, PDF, PowerPoint), regardless of how
        # many datasets a researcher had marked ``exportable: false``.
        # See the architecture audit finding this closes.
        sources = r.all_source_datasets
        if any(
            not is_exportable(policy_doc, Path(src).name) for src in sources
        ):
            excluded_dataset_count += 1
            continue
        filtered_results.append(r)
    results = filtered_results
    chain_ok, n_releases, _ = release_ledger.verify_chain(cwd)
    try:
        usage = usage_meter.summarize(cwd)
    except Exception:  # noqa: BLE001
        usage = {}
    figures = _collect_report_figures(cwd)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    # ---- gather per-result material once ----
    entries: list[dict[str, Any]] = []
    n_warnings_total = 0
    for row in results:
        payload = row.sanitized_payload or {}
        try:
            verification = verify_payload(payload)
        except Exception as exc:  # noqa: BLE001 — degradation remains visible
            verification = {
                "status": "unavailable",
                "checks": [{
                    "status": "warn",
                    "detail": (
                        "Result verification was unavailable "
                        f"({type(exc).__name__}); this is not a pass."
                    ),
                }],
            }
        try:
            table_md = render_table(payload)
        except Exception:  # noqa: BLE001
            table_md = None
        warns = [c for c in (verification or {}).get("checks", [])
                 if c.get("status") == "warn"]
        passes = [c for c in (verification or {}).get("checks", [])
                  if c.get("status") == "pass"]
        n_warnings_total += len(warns)
        entries.append({
            "row": row, "payload": payload, "table_md": table_md,
            "warns": warns, "passes": passes,
        })

    try:
        from sift.verification import session_report
        # ``source_dataset`` must come from the store row's own
        # column, not the sanitized payload -- no sanitizer analysis
        # shape has ever included a "source_dataset" key in the
        # payload itself (see the identical fix a few lines up, for
        # the exportability filter). Reading it from the payload here
        # silently returned None for every entry, which made the
        # sample-size-drift check inside session_report permanently
        # inert for every replication-package / report export, even
        # though the live UI's Verification panel (ui.py's
        # get_session_verification) already read the row column
        # correctly.
        session_block = session_report([{
            "label": e["row"].label,
            "analysis_type": e["row"].analysis_type,
            "payload": e["payload"],
            "source_dataset": e["row"].source_dataset,
            "source_datasets": list(e["row"].all_source_datasets),
            "script_run_id": e["row"].script_run_id,
        } for e in entries])
    except Exception as exc:  # noqa: BLE001 — degradation remains visible
        session_block = {"checks": [{
            "status": "warn",
            "detail": (
                "Across-result verification was unavailable "
                f"({type(exc).__name__}); this is not a pass."
            ),
        }]}

    return {
        "entries": entries,
        "figures": figures,
        "stamp": stamp,
        "n_releases": n_releases,
        "chain_ok": chain_ok,
        "n_warnings_total": n_warnings_total,
        "usage": usage,
        "excluded_dataset_count": excluded_dataset_count,
        "session_block": session_block,
        "ai_statement": ai_use_statement(cwd),
    }


