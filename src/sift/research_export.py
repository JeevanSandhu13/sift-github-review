"""Sift — research outputs: LaTeX tables, replication packages, disclosure reports.

Three researcher-facing exports, all built from material Sift already
holds. None of them adds a capability the model can invoke and none
widens the privacy boundary: every input is either already-sanitized
(the result store, the release ledger) or researcher-owned and
staying local (script sources, run logs). Export is a *user* action,
driven from the UI bridge, not a tool the model can call.

Why these three:

- **LaTeX tables** (``render_latex_table``). Applied researchers write
  in LaTeX. Sift already renders a canonical markdown table per
  analysis type; the numbers in those tables are the disclosure-
  controlled ones. Re-formatting the same values as ``booktabs``
  removes a manual transcription step that is both tedious and a
  genuine source of published errors.

- **Replication package** (``build_replication_package``). Journals
  and funders increasingly require replication materials. Sift is in
  an unusually good position to produce them: it already retains
  every script it ran, every sanitized result, the transformations
  applied, and the runtime environment. Assembling that into a
  directory is bookkeeping Sift can do perfectly and a human does
  badly under deadline.

- **Disclosure report** (``build_disclosure_report``). A researcher
  working under an IRB protocol or a data-use agreement is often
  required to state what left the secure environment. The release
  ledger is exactly that record. Rendering it as a reviewable
  document is what lets a data-governance office sign off on Sift
  rather than a researcher arguing from first principles.

Honesty constraints, enforced here:

- Nothing in an export is generated by a language model. Every number
  comes from a stored sanitized payload; every claim about what
  crossed comes from the ledger.
- The disclosure report states plainly that it records *what* was
  released, and that the ledger is tamper-evident (hash-chained), not
  tamper-proof, and not a formal privacy guarantee. It reports the
  chain-verification result rather than asserting integrity.
- Exports never contain raw data. They cannot: the store holds only
  post-sanitizer payloads. Script *sources* are included (they are the
  researcher's own code and are needed for replication) and may
  reference variable names — never values.
"""

