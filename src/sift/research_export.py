# ``result_render._escape_table_cell`` escapes a data-origin ``|``
# inside a cell as ``\|`` (backslash first escaped to ``\\`` so the
# pipe-escaping backslash is never itself ambiguous -- see that
# function's own docstring) specifically so a category label like
# "A | B" doesn't derail the table's column count. Splitting a row on
# every raw ``|`` character -- what both table parsers below used to
# do -- undoes that protection: a cell containing an escaped pipe
# gets split into extra columns, shifting every following cell in the
# row out of alignment. ``_UNESCAPED_PIPE`` only matches a ``|`` NOT
# preceded by a backslash; ``_unescape_cell`` then reverses the
# escape in the opposite order it was applied (pipe-unescape before
# backslash-unescape), the same asymmetric-order requirement
# ``_escape_table_cell``'s docstring calls out for the forward
# direction.
_UNESCAPED_PIPE = re.compile(r"(?<!\\)\|")


def _unescape_cell(s: str) -> str:
    return s.replace("\\|", "|").replace("\\\\", "\\")


def _cells_from_md_row(line: str) -> list[str]:
    parts = _UNESCAPED_PIPE.split(line.strip().strip("|"))
    return [_unescape_cell(c.strip()) for c in parts]


def _parse_md_table(md_table: str) -> tuple[list[str], list[list[str]], list[str]] | None:
    """Parse the renderer's canonical pipe table into (header, rows, caption).

    Shared by the PDF and PowerPoint exporters. Returns ``None`` if
    ``md_table`` isn't a well-formed pipe table.
    """
    lines = [ln for ln in md_table.splitlines() if ln.strip()]
    rows = [ln for ln in lines if ln.lstrip().startswith("|")]
    if len(rows) < 2:
        return None

    header = _cells_from_md_row(rows[0])
    body = [_cells_from_md_row(r) for r in rows[2:]]  # row 1 is the separator
    caption = [ln for ln in lines if not ln.lstrip().startswith("|")]
    return header, body, caption


