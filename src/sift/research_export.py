# ---------------------------------------------------------------------------
# Codebook / data dictionary
# ---------------------------------------------------------------------------
#
# Nearly every discipline that handles microdata has to produce a data
# dictionary at some point: IRB submissions require them, archives
# (ICPSR, openICPSR, Dataverse) require them, journals increasingly
# require them, and every co-author asks for one. The material is
# exactly what Sift already computes — schema labels and value labels
# from the file's own metadata, missingness and ranges from the local
# profile — so assembling it is bookkeeping Sift can do exactly.
#
# Audience note, because it matters for what may appear here: the
# codebook is a RESEARCHER-LOCAL export, like the dataset profile. It
# is built from full-depth schema extraction regardless of the
# per-dataset Permission ceiling, because the ceiling governs what the
# *model* may see, not what the researcher may see of their own data.
# Nothing here crosses to the model; the export lands in the session
# directory and goes wherever the researcher sends it.

def build_codebook(cwd: Path) -> dict[str, str]:
    """Build the session codebook. Returns ``{"markdown", "csv"}``.

    One section per dataset in the session. Datasets that cannot be
    read (malformed, over the size ceiling with no partial reader)
    get an explicit entry saying so — silently skipping a file would
    make the codebook claim completeness it doesn't have.
    """
    import csv as _csv
    import io

    from sift.dataset_profile import profile_dataset
    from sift.policy import is_exportable, load_policy
    from sift.schema import extract
    from sift.system_prompt import scan_datasets
    from sift.text_safety import csv_formula_safe

    cwd = Path(cwd)
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    datasets = scan_datasets(cwd)
    policy_doc = load_policy(cwd)

    md: list[str] = [
        "# Codebook", "",
        f"Generated by Sift on {stamp}.", "",
        "Variable names, labels and value labels come from each file's "
        "own metadata; missingness, distinct counts and ranges are "
        "computed locally. This document is produced on the "
        "researcher's machine for the researcher's use — none of it "
        "is sent to a model by this export.", "",
    ]
    csv_buf = io.StringIO()
    writer = _csv.writer(csv_buf)
    writer.writerow([
        "dataset", "variable", "type", "label", "value_labels",
        "missing_pct", "distinct", "min", "max",
    ])

    if not datasets:
        md += ["_No datasets in this session._", ""]

    for path in datasets:
        md += [f"## {path.name}", ""]
        if not is_exportable(policy_doc, path.name):
            # The researcher (or an inherited policy) has marked this
            # dataset non-exportable: analysis inside Sift is fine,
            # but no artifact describing it leaves the session state.
            # An explicit, visible line — not a silent omission — so
            # the codebook doesn't quietly claim completeness it
            # doesn't have, same principle the "UNREADABLE" entry
            # right below already applies to unreadable files.
            md += [
                "_Excluded from this export by dataset policy "
                "(`exportable: false` in `.sift/policy.json`)._", "",
            ]
            writer.writerow([
                csv_formula_safe(path.name), "", "", "EXCLUDED_BY_POLICY",
                "", "", "", "", "",
            ])
            continue
        try:
            schema = extract(path, "names_types_labels")
        except Exception as e:  # noqa: BLE001 — malformed files are expected
            md += [f"_Could not read this file "
                   f"({type(e).__name__})._", ""]
            writer.writerow([
                csv_formula_safe(path.name), "", "", "UNREADABLE", "",
                "", "", "", "",
            ])
            continue
        profile = profile_dataset(path)
        prof_vars = ({v["name"]: v for v in profile.get("variables", [])}
                     if profile.get("ok") else {})

        header_bits: list[str] = []
        if profile.get("ok"):
            rows_label = (f"{profile['rows']:,} rows"
                          if profile.get("rows_exact")
                          else f"~{profile['rows']:,} rows")
            header_bits += [rows_label, f"{profile['columns']} variables",
                            f"{profile['missing_pct']}% missing overall"]
            if profile.get("sampled"):
                header_bits.append(
                    f"statistics from the first "
                    f"{profile['rows_profiled']:,} rows (large file)")
        else:
            header_bits.append(
                f"statistics unavailable: {profile.get('reason', '?')}")
        md += [" · ".join(header_bits), ""]

        design = (profile.get("survey_design_columns") or []
                  if profile.get("ok") else [])
        if design:
            md += [
                "**Survey design variables detected** — estimates from "
                "this dataset should use design-aware methods "
                "(weights, strata, clustering):", "",
            ]
            md += [f"- `{d['name']}` — {d['role']}" for d in design]
            md.append("")
        md += ["| Variable | Type | Label | Values | Missing | Range |",
               "|---|---|---|---|---|---|"]
        for var in schema.get("variables", []):
            name = str(var.get("name", ""))
            vtype = str(var.get("type", ""))
            label = str(var.get("label", "") or "")
            vlabels = var.get("value_labels") or {}
            values = "; ".join(
                f"{k} = {v}" for k, v in list(vlabels.items())[:12])
            if var.get("value_labels_truncated"):
                values += f" … ({var.get('value_labels_total')} total)"
            pv = prof_vars.get(name, {})
            missing = (f"{pv.get('missing_pct')}%"
                       if pv.get("missing_pct") is not None else "")
            rng = ""
            if pv.get("min") is not None and pv.get("max") is not None:
                rng = f"{pv['min']} – {pv['max']}"
            distinct = pv.get("distinct", "")

            def _cell(text: str) -> str:
                return text.replace("|", "\\|")

            md.append(
                f"| `{_cell(name)}` | {_cell(vtype)} | {_cell(label)} | "
                f"{_cell(values)} | {missing} | {_cell(rng)} |")
            # ``path.name`` (a data-file's own filename), ``name``,
            # ``label``, and every value-label string below all
            # originate from the researcher's (or a malicious third
            # party's, per this audit) data file — none of them are
            # Sift-authored constants, so every one gets the CSV
            # formula-injection guard before it reaches the writer.
            # ``vtype``/``missing_pct``/``distinct``/``min``/``max``
            # are Sift-computed (a type name, a percentage, a count,
            # numeric bounds) and never start with a formula-trigger
            # character, so they're left as-is.
            value_labels_str = "; ".join(
                f"{k}={v}" for k, v in vlabels.items()
            )
            writer.writerow([
                csv_formula_safe(path.name),
                csv_formula_safe(name),
                vtype,
                csv_formula_safe(label),
                csv_formula_safe(value_labels_str),
                pv.get("missing_pct", ""), distinct,
                pv.get("min", ""), pv.get("max", ""),
            ])
        md.append("")

    return {"markdown": "\n".join(md), "csv": csv_buf.getvalue()}


# ---------------------------------------------------------------------------
# AI-use disclosure statement
# ---------------------------------------------------------------------------
#
# Journals, funders and universities increasingly require authors to
# state how AI tools were used. Researchers currently write these
# from memory, which produces statements that are vague where they
# should be specific and — worse — specific where the author is
# guessing. Sift can generate the statement from session facts:
# which models were used, how many interactions, what categorically
# did and did not cross to the provider, and what verification ran.
#
# Every sentence below is either a fixed architectural fact of Sift
# (enforced elsewhere in the codebase and its tests) or is computed
# from this session's records. Nothing is adjusted for tone. If a
# fact is unavailable (no usage recorded), the sentence is omitted
# rather than estimated.

def ai_use_statement(cwd: Path) -> str:
    """A paste-ready AI-use disclosure paragraph for publications."""
    from sift import release_ledger, usage_meter

    cwd = Path(cwd)
    try:
        usage = usage_meter.summarize(cwd)
    except Exception:  # noqa: BLE001
        usage = {}
    _chain_ok, n_releases, _ = release_ledger.verify_chain(cwd)

    models = sorted({
        str(row.get("model"))
        for row in usage.get("by_model", [])
        if row.get("model") and row.get("model") != "unknown"
    })
    if models:
        model_clause = (
            "the large language model"
            + ("s " if len(models) > 1 else " ")
            + ", ".join(f"`{m}`" for m in models)
        )
    else:
        model_clause = "a large language model"
    turns = usage.get("turns")
    turns_clause = ""
    if isinstance(turns, int) and turns > 0:
        noun = "turn" if turns == 1 else "turns"
        turns_clause = f" across {turns} interactive {noun}"

    return (
        f"Statistical analysis was conducted using Sift, a local "
        f"analysis environment in which {model_clause} proposed "
        f"analytical methods, generated statistical code, and "
        f"interpreted disclosure-controlled summary results"
        f"{turns_clause}. The raw data remained on the researcher's "
        f"machine throughout: the model had no direct access to the "
        f"dataset and received only variable-level metadata (as "
        f"permitted per dataset by the researcher) and aggregate "
        f"statistical results that had passed a statistical-"
        f"disclosure-control layer applying small-cell suppression, "
        f"sample-size-scaled precision limits, and minimum-subgroup "
        f"thresholds. Generated code was executed locally in a "
        f"sandboxed environment with network access denied. "
        f"{n_releases} disclosure-controlled "
        f"{'release' if n_releases == 1 else 'releases'} to the model "
        f"were recorded in a tamper-evident log available from the "
        f"authors. Deterministic diagnostic checks (reported "
        f"alongside each result) were computed by the software "
        f"rather than by the model. The authors reviewed all "
        f"analyses and remain responsible for the reported results. "
        f"This statement was generated from the session's own "
        f"records by Sift."
    )
