def capture_environment() -> dict[str, Any]:
    """Record the software environment for reproducibility.

    Version numbers only — no paths, no environment variables, no
    machine identifiers. A replication package should tell the next
    person what to install, not where the original author kept their
    files or what their username was.
    """
    env: dict[str, Any] = {
        "captured_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "python_version": sys.version.split()[0],
        "platform": platform.system(),
        "platform_release": platform.release(),
        "machine": platform.machine(),
    }
    packages: dict[str, str] = {}
    for mod in ("pandas", "numpy", "statsmodels", "scipy", "sklearn",
                "pyarrow", "matplotlib", "linearmodels", "pyfixest"):
        try:
            packages[mod] = __import__(mod).__version__
        except Exception:  # noqa: BLE001 — absent packages are simply absent
            continue
    env["python_packages"] = packages
    try:
        from sift.env_detect import detect_environment
        detected = detect_environment()
        for name in ("r", "stata", "python"):
            val = getattr(detected, name, None)
            if val:
                env[f"{name}_available"] = True
    except Exception:  # noqa: BLE001
        pass
    return env


