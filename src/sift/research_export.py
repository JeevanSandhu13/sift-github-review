# PowerPoint export
# ---------------------------------------------------------------------------
#
# A one-idea-per-slide deck for a lab meeting or an advisor update --
# same material, same store query, same sanitized payloads as every
# other export in this module. python-pptx is pure Python (no
# LibreOffice/PowerPoint dependency).

_PPTX_MAX_TABLE_ROWS = 12  # a slide is a much smaller canvas than a page


def _pptx_add_bullets(slide: Any, box: Any, lines: list[str]) -> None:
    tf = box.text_frame
    tf.word_wrap = True
    first = True
    for line in lines:
        p = tf.paragraphs[0] if first else tf.add_paragraph()
        p.text = line
        first = False


def build_analysis_report_pptx(cwd: Path, dest: Path) -> None:
    """Write the analysis report as a PowerPoint deck to ``dest``.

    Raises on genuine failure -- callers (the UI bridge) are expected
    to catch and surface, exactly like every other export builder in
    this module.
    """
    from pptx import Presentation
    from pptx.util import Inches, Pt

    cwd = Path(cwd)
    dest = Path(dest)
    material = _gather_report_material(cwd)
    entries = material["entries"]
    figures = material["figures"]
    stamp = material["stamp"]
    n_releases = material["n_releases"]
    chain_ok = material["chain_ok"]
    n_warnings_total = material["n_warnings_total"]
    usage = material["usage"]
    excluded_dataset_count = material["excluded_dataset_count"]
    session_block = material["session_block"]

    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    title_layout = prs.slide_layouts[0]
    bullet_layout = prs.slide_layouts[1]
    blank_layout = prs.slide_layouts[6]

    title_slide = prs.slides.add_slide(title_layout)
    title_slide.shapes.title.text = "Analysis report"
    if title_slide.placeholders and len(title_slide.placeholders) > 1:
        title_slide.placeholders[1].text = (
            f"Generated by Sift on {stamp}\n"
            f"Assembled from stored, disclosure-controlled results — "
            f"no slide content was written by a language model.")

    summary_slide = prs.slides.add_slide(bullet_layout)
    summary_slide.shapes.title.text = "Summary"
    summary_bits = [
        f"Results: {len(entries)}",
        f"Verification warnings across all results: {n_warnings_total}",
        f"Disclosures to the external model: {n_releases} "
        f"(ledger chain {'verified' if chain_ok else 'INCONSISTENT'})",
    ]
    if excluded_dataset_count:
        summary_bits.append(
            f"Results excluded by dataset policy: {excluded_dataset_count}")
    turns = usage.get("turns")
    if isinstance(turns, int) and turns > 0:
        tok = usage.get("total_tokens", 0)
        summary_bits.append(f"Model usage: {turns} turns, {tok:,} tokens")
    body_ph = summary_slide.placeholders[1]
    _pptx_add_bullets(summary_slide, body_ph, summary_bits)

    if not entries:
        empty_slide = prs.slides.add_slide(bullet_layout)
        empty_slide.shapes.title.text = "Findings"
        _pptx_add_bullets(empty_slide, empty_slide.placeholders[1],
                          ["No analysis results have been recorded in "
                           "this session yet."])

    for i, entry in enumerate(entries, start=1):
        row = entry["row"]
        payload = entry["payload"]
        slide = prs.slides.add_slide(blank_layout)
        title_box = slide.shapes.add_textbox(Inches(0.4), Inches(0.25),
                                             Inches(12.5), Inches(0.7))
        title_box.text_frame.text = f"{i}. {row.label or row.analysis_type}"
        title_box.text_frame.paragraphs[0].font.size = Pt(28)
        title_box.text_frame.paragraphs[0].font.bold = True

        n = payload.get("n")
        meta_bits = [row.analysis_type, row.language]
        if isinstance(n, int):
            meta_bits.append(f"N = {n:,}")
        meta_box = slide.shapes.add_textbox(Inches(0.4), Inches(0.95),
                                            Inches(12.5), Inches(0.35))
        meta_box.text_frame.text = " · ".join(meta_bits)
        meta_box.text_frame.paragraphs[0].font.size = Pt(12)
        meta_box.text_frame.paragraphs[0].font.italic = True

        top = 1.4
        parsed = _parse_md_table(entry["table_md"]) if entry["table_md"] else None
        if parsed:
            header, rows_, caption = parsed
            shown = rows_[:_PPTX_MAX_TABLE_ROWS]
            n_rows = len(shown) + 1
            n_cols = len(header)
            table_h = min(4.6, 0.4 * n_rows + 0.3)
            gfx = slide.shapes.add_table(
                n_rows, n_cols, Inches(0.4), Inches(top),
                Inches(12.5), Inches(table_h))
            tbl = gfx.table
            for c, h in enumerate(header):
                tbl.cell(0, c).text = str(h)
                for para in tbl.cell(0, c).text_frame.paragraphs:
                    para.font.size = Pt(12)
                    para.font.bold = True
            for r, rvals in enumerate(shown, start=1):
                for c, val in enumerate(rvals):
                    tbl.cell(r, c).text = str(val)
                    for para in tbl.cell(r, c).text_frame.paragraphs:
                        para.font.size = Pt(11)
            top += table_h + 0.15
            if len(rows_) > _PPTX_MAX_TABLE_ROWS:
                note_box = slide.shapes.add_textbox(
                    Inches(0.4), Inches(top), Inches(12.5), Inches(0.3))
                note_box.text_frame.text = (
                    f"… {len(rows_) - _PPTX_MAX_TABLE_ROWS} more row(s) — "
                    f"see the full report for the complete table.")
                note_box.text_frame.paragraphs[0].font.size = Pt(10)
                note_box.text_frame.paragraphs[0].font.italic = True
                top += 0.35

        verif_lines = [f"⚠ {c.get('detail', '')}" for c in entry["warns"]]
        verif_lines += [f"✓ {c.get('detail', '')}" for c in entry["passes"]]
        if verif_lines and top < 6.9:
            vbox = slide.shapes.add_textbox(Inches(0.4), Inches(top),
                                            Inches(12.5), Inches(7.3 - top))
            _pptx_add_bullets(slide, vbox, verif_lines[:8])
            if len(verif_lines) > 8:
                p = vbox.text_frame.add_paragraph()
                p.text = f"… {len(verif_lines) - 8} more check(s) — see the full report."
                p.font.italic = True
                p.font.size = Pt(10)

    for fig in figures:
        try:
            import base64 as _b64
            import io as _io
            blob = _b64.b64decode(fig["b64"])
            slide = prs.slides.add_slide(blank_layout)
            title_box = slide.shapes.add_textbox(Inches(0.4), Inches(0.25),
                                                 Inches(12.5), Inches(0.6))
            title_box.text_frame.text = f"{fig['label']} ({fig['kind']})"
            title_box.text_frame.paragraphs[0].font.size = Pt(22)
            title_box.text_frame.paragraphs[0].font.bold = True
            slide.shapes.add_picture(_io.BytesIO(blob), Inches(1.0),
                                     Inches(1.1), height=Inches(5.8))
        except Exception:  # noqa: BLE001 — one bad image must not sink the deck
            continue

    if session_block.get("checks"):
        slide = prs.slides.add_slide(bullet_layout)
        slide.shapes.title.text = "Across-result checks"
        lines = []
        for c in session_block["checks"]:
            mark = "⚠" if c["status"] == "warn" else "✓"
            lines.append(f"{mark} {c['detail']}")
        _pptx_add_bullets(slide, slide.placeholders[1], lines)

    ai_slide = prs.slides.add_slide(bullet_layout)
    ai_slide.shapes.title.text = "AI-use disclosure statement"
    _pptx_add_bullets(ai_slide, ai_slide.placeholders[1],
                      [material["ai_statement"]])

    lim_slide = prs.slides.add_slide(bullet_layout)
    lim_slide.shapes.title.text = "Limitations"
    _pptx_add_bullets(lim_slide, lim_slide.placeholders[1], [
        "Verification verdicts are conventional heuristics for drawing "
        "attention, not proofs of validity; their thresholds are cited "
        "in Sift's source.",
        "A check that is absent was not computed; that is not the same "
        "as passing.",
        "The disclosure count records what crossed to the model. It "
        "does not bound what could be inferred from those releases in "
        "combination.",
    ])

    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary_name = tempfile.mkstemp(
        prefix=f".{dest.name}.", suffix=".pptx", dir=dest.parent,
    )
    os.close(fd)
    temporary = Path(temporary_name)
    try:
        prs.save(str(temporary))
        with temporary.open("rb+") as handle:
            os.fsync(handle.fileno())
        os.chmod(temporary, 0o600)
        os.replace(temporary, dest)
    finally:
        temporary.unlink(missing_ok=True)


def _html_escape(text: Any) -> str:
    return (str("" if text is None else text)
            .replace("&", "&amp;").replace("<", "&lt;")
            .replace(">", "&gt;").replace('"', "&quot;"))


def _md_table_to_html(md_table: str) -> str:
    """Convert the canonical pipe table to HTML.

    The renderer's output is strictly shaped (header, separator,
    rows), so a purpose-built converter is safer than pulling in a
    markdown dependency for one table shape.
    """
    lines = [ln for ln in md_table.splitlines() if ln.strip()]
    rows = [ln for ln in lines if ln.lstrip().startswith("|")]
    if len(rows) < 2:
        return f"<pre>{_html_escape(md_table)}</pre>"

    header = _cells_from_md_row(rows[0])
    body = [_cells_from_md_row(r) for r in rows[2:]]  # row 1 is the separator
    out = ["<table><thead><tr>"]
    out += [f"<th>{_html_escape(h)}</th>" for h in header]
    out.append("</tr></thead><tbody>")
    for cells in body:
        out.append("<tr>")
        out += [f"<td>{_html_escape(c)}</td>" for c in cells]
        out.append("</tr>")
    out.append("</tbody></table>")
    caption = [ln for ln in lines if not ln.lstrip().startswith("|")]
    if caption:
        out.append(f"<p class='caption'>{_html_escape(' '.join(caption))}</p>")
    return "".join(out)


