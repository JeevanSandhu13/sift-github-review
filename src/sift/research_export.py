# LaTeX special characters. Data-origin strings (variable names, value
# labels) reach here already text-safety-sanitized, but sanitization
# targets prompt injection, not TeX syntax: a variable legitimately
# named ``income_net`` or ``share_%`` would still break compilation or
# silently typeset wrong. Escaping is therefore about correctness of
# the produced document.
_LATEX_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}",
    "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


class Raw(str):
    """A string that is already valid LaTeX and must not be escaped.

    Sift-authored markup (column heads like ``$p$-value``, note lines
    containing ``$R^2$``) and data-origin text (variable names, value
    labels) travel through the same table builder. Escaping everything
    mangles our own math mode; escaping nothing lets a variable named
    ``share_%`` break compilation. Marking Sift-authored fragments
    ``Raw`` keeps the default safe — anything not explicitly marked is
    escaped — so a new call site cannot leak unescaped data by
    omission.
    """

    __slots__ = ()


def latex_escape(text: Any) -> str:
    """Escape a value for safe inclusion in a LaTeX document body.

    ``Raw`` values pass through untouched; everything else is escaped.
    """
    if isinstance(text, Raw):
        return str(text)
    raw = str("" if text is None else text)
    # Flatten all whitespace first. A newline inside a cell splits the
    # row across two physical lines, so the table stops having a
    # consistent column count and LaTeX either errors or typesets
    # something wrong. ``text_safety`` already normalises whitespace on
    # the way into the store, so this is defence in depth for values
    # that reach the exporter by another route.
    raw = " ".join(raw.split())
    return "".join(_LATEX_ESCAPES.get(ch, ch) for ch in raw)


def _latex_pvalue(x: Any) -> Raw:
    """Format a p-value for LaTeX, with relational operators in math mode.

    ``_fmt_pvalue`` emits ``<0.001`` / ``>0.999``. A bare ``<`` in LaTeX
    text mode typesets as an inverted exclamation mark, so the operator
    has to enter math mode to render correctly.
    """
    formatted = _fmt_pvalue(x)
    if formatted.startswith("<"):
        return Raw("$<$" + latex_escape(formatted[1:]))
    if formatted.startswith(">"):
        return Raw("$>$" + latex_escape(formatted[1:]))
    return Raw(latex_escape(formatted))


def _as_dict(value: Any) -> dict[str, Any]:
    """Return ``value`` when it is a dict, else an empty dict.

    ``payload.get("standard_errors") or {}`` looks equivalent but is
    not: any truthy non-dict (a stray float, a string) survives the
    ``or`` and then raises on ``.get``. Payload shapes are not
    guaranteed field-by-field at this layer, so coercion is explicit.
    """
    return value if isinstance(value, dict) else {}


def _booktabs(
    header: list[str],
    rows: list[list[str]],
    *,
    caption: str | None = None,
    label: str | None = None,
    align: str | None = None,
) -> str:
    """Assemble a ``booktabs`` table environment.

    Left-aligns the first column (terms / labels) and right-aligns the
    rest (numbers) unless told otherwise — the standard convention for
    a results table, and the one that makes decimal points line up.
    """
    ncols = len(header)
    colspec = align or ("l" + "r" * (ncols - 1))
    lines = [
        "\\begin{table}[htbp]",
        "\\centering",
    ]
    if caption:
        lines.append(f"\\caption{{{latex_escape(caption)}}}")
    if label:
        lines.append(f"\\label{{{label}}}")
    lines += [
        f"\\begin{{tabular}}{{{colspec}}}",
        "\\toprule",
        " & ".join(latex_escape(h) for h in header) + " \\\\",
        "\\midrule",
    ]
    for row in rows:
        lines.append(" & ".join(latex_escape(c) for c in row) + " \\\\")
    lines += [
        "\\bottomrule",
        "\\end{tabular}",
        "\\end{table}",
    ]
    return "\n".join(lines)


def render_latex_table(
    payload: dict[str, Any],
    *,
    caption: str | None = None,
    label: str | None = None,
) -> str | None:
    """Render a sanitized payload as a ``booktabs`` LaTeX table.

    Returns ``None`` for payload types with no dedicated LaTeX
    renderer, so callers fall back rather than emitting a malformed
    table. Requires ``\\usepackage{booktabs}`` in the preamble.
    """
    if not isinstance(payload, dict):
        return None
    ptype = payload.get("type")

    if ptype in ("linear_regression", "coefficient_table_with_fit_stats"):
        # Canonical regression-bucket type name plus its legacy
        # alias -- see verification.py's dispatch table (fixed
        # alongside this one) for the full rationale. Without the
        # canonical name here, every CURRENT regression result (the
        # single most common analysis type) silently got no LaTeX
        # table at all in the replication package, PDF, or PowerPoint
        # export -- render_latex_table fell through every branch and
        # returned None, and callers treat None as "nothing to render
        # for this type", not as an error, so this failed completely
        # silently.
        coefs = payload.get("coefficients") or {}
        if not isinstance(coefs, dict) or not coefs:
            return None
        ses = _as_dict(payload.get("standard_errors"))
        pvals = _as_dict(payload.get("p_values"))
        has_p = bool(isinstance(pvals, dict) and pvals)
        header = ["Term", "Estimate", "Std. Error"]
        if has_p:
            header.append(Raw("$p$-value"))
        rows = []
        for term, est in coefs.items():
            row = [str(term), _fmt_num(est), _fmt_num(ses.get(term))]
            if has_p:
                row.append(_latex_pvalue(pvals.get(term)))
            rows.append(row)
        notes = _regression_notes(payload)
        body = _booktabs(header, rows, caption=caption, label=label)
        return _with_notes(body, notes)

    if ptype == "descriptive":
        header = ["Statistic", "Value"]
        rows = []
        for key in ("n", "mean", "sd", "missing_count"):
            if key in payload:
                rows.append([
                    {"n": "N", "mean": "Mean", "sd": "SD",
                     "missing_count": "Missing"}[key],
                    _fmt_num(payload.get(key)),
                ])
        if not rows:
            return None
        var = payload.get("variable")
        return _booktabs(
            header, rows,
            caption=caption or (f"Descriptive statistics: {var}" if var else None),
            label=label,
        )

    if ptype == "frequency_table":
        counts = payload.get("counts")
        if not isinstance(counts, dict) or not counts:
            return None
        rows = [[str(k), _fmt_num(v)] for k, v in counts.items()]
        var = payload.get("variable")
        return _booktabs(
            ["Category", "Count"], rows,
            caption=caption or (f"Frequency: {var}" if var else None),
            label=label,
        )

    if ptype == "t_test":
        header = ["Quantity", "Value"]
        rows = []
        for key, disp in (
            ("statistic", Raw("$t$")), ("degrees_of_freedom", "df"),
            ("p_value", Raw("$p$")), ("mean_difference", "Mean difference"),
            ("ci_lower", "CI lower"), ("ci_upper", "CI upper"),
        ):
            if key in payload:
                val = (_latex_pvalue(payload[key]) if key == "p_value"
                       else _fmt_num(payload[key]))
                rows.append([disp, val])
        if not rows:
            return None
        return _booktabs(header, rows, caption=caption, label=label)

    if ptype == "correlation_matrix":
        variables = payload.get("variables")
        corrs = payload.get("correlations")
        if not isinstance(variables, list) or not isinstance(corrs, dict):
            return None
        header = [""] + [str(v) for v in variables]
        rows = []
        for rvar in variables:
            row = [str(rvar)]
            for cvar in variables:
                if rvar == cvar:
                    row.append("1")
                    continue
                corr_value = (corrs.get(f"{rvar}|{cvar}")
                              or corrs.get(f"{cvar}|{rvar}"))
                row.append(
                    _fmt_num(corr_value) if corr_value is not None else ""
                )
            rows.append(row)
        return _booktabs(header, rows, caption=caption, label=label)

    if ptype == "crosstab":
        counts = payload.get("counts")
        if not isinstance(counts, dict) or not counts:
            return None
        # Crosstab counts arrive keyed "row|col"; recover the grid.
        rows_seen: list[str] = []
        cols_seen: list[str] = []
        grid: dict[tuple[str, str], Any] = {}
        for key, val in counts.items():
            if "|" not in str(key):
                continue
            r, c = str(key).split("|", 1)
            if r not in rows_seen:
                rows_seen.append(r)
            if c not in cols_seen:
                cols_seen.append(c)
            grid[(r, c)] = val
        if not rows_seen or not cols_seen:
            return None
        header = [Raw("")] + cols_seen
        cross_body = [
            [r] + [_fmt_num(grid.get((r, c), "")) for c in cols_seen]
            for r in rows_seen
        ]
        return _booktabs(header, cross_body, caption=caption, label=label)

    if ptype == "magnitude_table":
        cells = payload.get("cells")
        if not isinstance(cells, dict) or not cells:
            return None
        rows = [[str(k), _fmt_num(v)] for k, v in cells.items()]
        agg = payload.get("aggregation")
        value_var = payload.get("value_variable")
        head = f"{agg} of {value_var}" if agg and value_var else "Value"
        return _booktabs([str(payload.get("row_variable") or "Group"), head],
                         rows, caption=caption, label=label)

    if ptype == "did_event_study":
        att = payload.get("att")
        if not isinstance(att, dict) or not att:
            return None
        ses = _as_dict(payload.get("standard_errors"))
        rows = []
        for group, series in att.items():
            if not isinstance(series, dict):
                continue
            for event_time, value in series.items():
                se = None
                if isinstance(ses, dict):
                    inner = ses.get(group)
                    if isinstance(inner, dict):
                        se = inner.get(event_time)
                rows.append([str(group), str(event_time),
                             _fmt_num(value), _fmt_num(se)])
        if not rows:
            return None
        did_notes: list[str] = []
        agg = _payload_num(payload, "aggregate_att")
        if agg is not None:
            leg = f"Aggregate ATT = {latex_escape(_fmt_num(agg))}"
            agg_se = _payload_num(payload, "aggregate_se")
            if agg_se is not None:
                leg += f" ({latex_escape(_fmt_num(agg_se))})"
            did_notes.append(Raw(leg))
        pre_p = _payload_num(payload, "pre_trends_p_value")
        if pre_p is not None:
            did_notes.append(Raw("Pre-trend test $p$ = "
                                 + latex_escape(_fmt_pvalue(pre_p))))
        table = _booktabs(["Cohort", "Event time", "ATT", "Std. Error"],
                          rows, caption=caption, label=label)
        return _with_notes(table, did_notes)

    if ptype == "rdd":
        rows = []
        for key, disp in (
            ("tau_conventional", "Conventional"),
            ("tau_bias_corrected", "Bias-corrected"),
            ("tau_robust", "Robust"),
        ):
            tau = _payload_num(payload, key)
            if tau is None:
                continue
            suffix = key.replace("tau_", "")
            rows.append([
                disp,
                _fmt_num(tau),
                _fmt_num(payload.get(f"se_{suffix}")),
                _latex_pvalue(payload.get(f"p_{suffix}")),
            ])
        if not rows:
            return None
        rdd_notes: list[str] = []
        for key, label_text in (("cutoff", "Cutoff"),
                                ("bandwidth_left", "Bandwidth (left)"),
                                ("bandwidth_right", "Bandwidth (right)"),
                                ("effective_n_left", "Effective N (left)"),
                                ("effective_n_right", "Effective N (right)")):
            rdd_value = _payload_num(payload, key)
            if rdd_value is not None:
                rdd_notes.append(Raw(f"{latex_escape(label_text)} = "
                                     f"{latex_escape(_fmt_num(rdd_value))}"))
        table = _booktabs([Raw("Estimator"), "Estimate", "Std. Error",
                           Raw("$p$-value")],
                          rows, caption=caption, label=label)
        return _with_notes(table, rdd_notes)

    if ptype == "kaplan_meier":
        rows = []
        median = _payload_num(payload, "median_survival_time")
        if median is not None:
            ci = ""
            lo = _payload_num(payload, "median_survival_ci_lower")
            hi = _payload_num(payload, "median_survival_ci_upper")
            if lo is not None and hi is not None:
                ci = f"[{_fmt_num(lo)}, {_fmt_num(hi)}]"
            rows.append(["Median survival", _fmt_num(median), ci])
        for horizon in ("1y", "3y", "5y", "10y"):
            survival_value = _payload_num(payload, f"survival_at_{horizon}")
            if survival_value is None:
                continue
            lo = _payload_num(payload, f"survival_at_{horizon}_ci_lower")
            hi = _payload_num(payload, f"survival_at_{horizon}_ci_upper")
            ci = (f"[{_fmt_num(lo)}, {_fmt_num(hi)}]"
                  if lo is not None and hi is not None else "")
            rows.append([
                f"Survival at {horizon}", _fmt_num(survival_value), ci,
            ])
        if not rows:
            return None
        km_notes: list[str] = []
        subj = _payload_num(payload, "n_subjects")
        events = _payload_num(payload, "n_failures")
        if subj is not None and events is not None:
            km_notes.append(Raw(f"{latex_escape(_fmt_num(subj))} subjects, "
                                f"{latex_escape(_fmt_num(events))} events"))
        lr_p = _payload_num(payload, "logrank_p_value")
        if lr_p is not None:
            km_notes.append(Raw("Log-rank $p$ = "
                                + latex_escape(_fmt_pvalue(lr_p))))
        table = _booktabs(["Quantity", "Estimate", Raw(r"95\% CI")], rows,
                          caption=caption, label=label)
        return _with_notes(table, km_notes)

    if ptype == "cluster_analysis":
        sizes = payload.get("cluster_sizes")
        if not isinstance(sizes, dict) or not sizes:
            return None
        rows = [[str(k), _fmt_num(v)] for k, v in sizes.items()]
        cluster_notes: list[str] = []
        for key, disp in (("silhouette_score", "Silhouette"),
                          ("ss_ratio", "Between/total SS")):
            cluster_value = _payload_num(payload, key)
            if cluster_value is not None:
                cluster_notes.append(Raw(f"{latex_escape(disp)} = "
                                         f"{latex_escape(_fmt_num(cluster_value))}"))
        method = payload.get("method")
        if isinstance(method, str) and method:
            cluster_notes.append(Raw(f"Method: {latex_escape(method)}"))
        table = _booktabs(["Cluster", "Observations"], rows,
                          caption=caption, label=label)
        return _with_notes(table, cluster_notes)

    if ptype == "factor_decomposition":
        loadings = payload.get("loadings")
        if not isinstance(loadings, dict) or not loadings:
            return None
        # ``loadings`` is {component: {variable: value}}.
        components = list(loadings.keys())
        factor_variables: list[str] = []
        for comp in components:
            inner = loadings.get(comp)
            if isinstance(inner, dict):
                for var in inner:
                    variable_text = str(var)
                    if variable_text not in factor_variables:
                        factor_variables.append(variable_text)
        if not factor_variables:
            return None
        header = ["Variable"] + [str(c) for c in components]
        rows = []
        for var in factor_variables:
            row = [var]
            for comp in components:
                inner = loadings.get(comp)
                row.append(_fmt_num(inner.get(var))
                           if isinstance(inner, dict) else "")
            rows.append(row)
        factor_notes: list[str] = []
        for key, disp in (("kmo", "KMO"), ("rmsea", "RMSEA"),
                          ("tli", "TLI")):
            factor_value = _payload_num(payload, key)
            if factor_value is not None:
                factor_notes.append(Raw(f"{latex_escape(disp)} = "
                                        f"{latex_escape(_fmt_num(factor_value))}"))
        table = _booktabs(header, rows, caption=caption, label=label)
        return _with_notes(table, factor_notes)

    if ptype == "marginal_effects":
        effects = payload.get("effects")
        if not isinstance(effects, dict) or not effects:
            return None
        ses = _as_dict(payload.get("standard_errors"))
        pvals = _as_dict(payload.get("p_values"))
        has_p = isinstance(pvals, dict) and bool(pvals)
        header = ["Variable", "Marginal effect", "Std. Error"]
        if has_p:
            header.append(Raw("$p$-value"))
        rows = []
        for var, val in effects.items():
            row = [str(var), _fmt_num(val),
                   _fmt_num(ses.get(var) if isinstance(ses, dict) else None)]
            if has_p:
                row.append(_latex_pvalue(pvals.get(var)))
            rows.append(row)
        notes = []
        method = payload.get("method")
        if isinstance(method, str) and method:
            notes.append(Raw(f"Estimand: {latex_escape(method)}"))
        n = _payload_num(payload, "n")
        if n is not None:
            notes.append(Raw(f"N = {latex_escape(_fmt_num(n))}"))
        table = _booktabs(header, rows, caption=caption, label=label)
        return _with_notes(table, notes)

    return None


def _payload_num(payload: dict[str, Any], key: str) -> float | None:
    """Numeric field accessor that ignores suppression markers.

    Sanitized payloads can carry a string like ``"<10"`` in a numeric
    slot when small-cell suppression fired. Those must never be
    coerced into a float — they are rendered verbatim by the table
    body, and note lines simply omit them.
    """
    val = payload.get(key)
    if isinstance(val, bool) or not isinstance(val, (int, float)):
        return None
    try:
        return float(val)
    except (OverflowError, ValueError):
        return None


def _regression_notes(payload: dict[str, Any]) -> list[str]:
    """Table notes carrying fit stats and the SE type actually used."""
    notes: list[str] = []
    n = payload.get("n")
    if isinstance(n, int):
        notes.append(Raw(f"N = {n:,}"))
    for key, disp in (("r_squared", "$R^2$"),
                      ("adj_r_squared", "Adj. $R^2$"),
                      ("pseudo_r_squared", "Pseudo $R^2$")):
        if key in payload:
            notes.append(Raw(f"{disp} = {latex_escape(_fmt_num(payload[key]))}"))
    robust = payload.get("robust_se_type")
    if isinstance(robust, str) and robust:
        pretty = {
            "classical": "classical standard errors",
            "cluster": "cluster-robust standard errors",
            "hac_newey_west": "Newey--West standard errors",
        }.get(robust, f"{robust.upper()} robust standard errors")
        notes.append(Raw(latex_escape(pretty)))
    return notes


def _with_notes(table: str, notes: list[str]) -> str:
    if not notes:
        return table
    note_line = (
        "\\begin{tablenotes}\\footnotesize\n\\item "
        + "; ".join(latex_escape(n) for n in notes)
        + "\n\\end{tablenotes}"
    )
    # Placed inside the table environment, before \end{table}. Requires
    # threeparttable for the notes environment; degrade gracefully by
    # commenting the requirement inline so a missing package is an
    # obvious fix rather than a cryptic error.
    return table.replace(
        "\\end{table}",
        "% requires \\usepackage{threeparttable} for tablenotes\n"
        + note_line + "\n\\end{table}",
    )


