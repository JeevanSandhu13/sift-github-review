# Reuse the on-screen formatters so an exported table is numerically
# identical to what the researcher already reviewed. Divergence between
# the screen and the paper is exactly the class of error this feature
# exists to prevent.
from sift.result_render import _fmt_num as _fmt_num_raw  # noqa: PLC2701
from sift.result_render import _fmt_pvalue as _fmt_pvalue_raw  # noqa: PLC2701


def _fmt_num(x: Any) -> str:
    """Format a number for a table cell, tolerating pathological input.

    Delegates to the shared renderer so exported tables carry exactly
    the same numerals the researcher reviewed on screen. The guard is
    for values that renderer cannot represent: Python integers are
    unbounded, and one larger than roughly 1.8e308 raises inside
    ``float()``. Those are not plausible statistics, but a payload can
    carry one, and a single bad cell must not abort an entire
    replication package. Rendering it as ``str`` keeps the value
    visible and the table well-formed.
    """
    try:
        return _fmt_num_raw(x)
    except (OverflowError, ValueError, TypeError):
        try:
            return str(x)
        except Exception:  # noqa: BLE001
            return ""


def _fmt_pvalue(x: Any) -> str:
    """``_fmt_pvalue`` with the same tolerance as :func:`_fmt_num`."""
    try:
        return _fmt_pvalue_raw(x)
    except (OverflowError, ValueError, TypeError):
        return ""


